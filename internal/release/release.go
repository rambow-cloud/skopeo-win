// Package release validates manually selected release tags and publishes immutable assets.
package release

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

const LegacyTag = "v1.23.0"

var stable = regexp.MustCompile(`^v(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$`)

type Ref struct {
	Ref    string `json:"ref"`
	Object struct {
		Type string `json:"type"`
		SHA  string `json:"sha"`
	} `json:"object"`
}

type Asset struct {
	Name   string `json:"name"`
	Digest string `json:"digest"`
}

type Release struct {
	ID     int64   `json:"id"`
	Tag    string  `json:"tag_name"`
	Body   string  `json:"body"`
	Draft  bool    `json:"draft"`
	Assets []Asset `json:"assets"`
}

func marker(runID string) string { return "<!-- skopeo-win-release-run:" + runID + " -->" }

func parse(tag string) ([3]uint64, bool) {
	var v [3]uint64
	parts := stable.FindStringSubmatch(tag)
	if parts == nil {
		return v, false
	}
	for i := range v {
		n, err := strconv.ParseUint(parts[i+1], 10, 64)
		if err != nil {
			return v, false
		}
		v[i] = n
	}
	return v, true
}

func (m Manager) checkTag(refs []Ref, tag string) error {
	for _, ref := range refs {
		if ref.Ref != "refs/tags/"+tag {
			continue
		}
		commit := ref.Object.SHA
		if ref.Object.Type == "tag" {
			// The commits endpoint peels annotated tags to their source commit.
			data, err := m.Run("api", "repos/"+m.Repo+"/commits/"+tag, "--jq", ".sha")
			if err != nil {
				return err
			}
			commit = strings.TrimSpace(string(data))
		} else if ref.Object.Type != "commit" {
			return fmt.Errorf("release tag must identify a commit")
		}
		if commit != m.Commit {
			return fmt.Errorf("refusing to move existing tag %s", tag)
		}
		return nil
	}
	return fmt.Errorf("release tag %s is missing", tag)
}

func validateTagState(tag, runID string, refs []Ref, releases []Release) error {
	v, ok := parse(tag)
	if !ok || tag == LegacyTag || v[0] == 0 || v[0] > 65535 || v[1] > 65535 || v[2] > 65535 {
		return fmt.Errorf("invalid independent Store-compatible release tag %q", tag)
	}
	for _, r := range releases {
		if r.Tag == tag && !strings.Contains(r.Body, marker(runID)) {
			return fmt.Errorf("release %s belongs to a different run", tag)
		}
	}
	// Ignore the selected pre-existing tag and the reserved legacy release.
	// Other tags, drafts and releases reserve their version; never publish backwards.
	tags := make([]string, 0, len(refs)+len(releases))
	for _, ref := range refs {
		tags = append(tags, strings.TrimPrefix(ref.Ref, "refs/tags/"))
	}
	for _, r := range releases {
		tags = append(tags, r.Tag)
	}
	for _, other := range tags {
		if other == tag || other == LegacyTag {
			continue
		}
		previous, valid := parse(other)
		if valid && (previous[0] > v[0] || previous[0] == v[0] && (previous[1] > v[1] || previous[1] == v[1] && previous[2] > v[2])) {
			return fmt.Errorf("release tag %s is older than reserved version %s", tag, other)
		}
	}
	return nil
}

func (m Manager) checkMainHistory() error {
	data, err := m.Run("api", "repos/"+m.Repo+"/compare/"+m.Commit+"...main", "--jq", ".merge_base_commit.sha")
	if err != nil {
		return err
	}
	if strings.TrimSpace(string(data)) != m.Commit {
		return fmt.Errorf("release source must belong to main history")
	}
	return nil
}

// PlanTag uses an existing maintainer-created tag; it never allocates a version.
func (m Manager) PlanTag(tag string) (string, error) {
	if err := validateTagState(tag, m.RunID, nil, nil); err != nil {
		return "", err
	}
	refs, releases, err := m.State()
	if err != nil {
		return "", err
	}
	if err := validateTagState(tag, m.RunID, refs, releases); err != nil {
		return "", err
	}
	if err := m.checkTag(refs, tag); err != nil {
		return "", err
	}
	if err := m.checkMainHistory(); err != nil {
		return "", err
	}
	return strings.TrimPrefix(tag, "v"), nil
}

type Runner func(args ...string) ([]byte, error)

func GH(args ...string) ([]byte, error) {
	cmd := exec.Command("gh", args...)
	cmd.Stderr = os.Stderr
	return cmd.Output()
}

type Manager struct {
	Run                 Runner
	Repo, Commit, RunID string
	Summary             string
}

// Notes captures a reviewed summary together with the exact build provenance.
// Existing published notes are never regenerated by publication retries.
func (m Manager) Notes(version string) (string, error) {
	summary := strings.TrimSpace(m.Summary)
	if summary == "" {
		return "", fmt.Errorf("a reviewed release summary is required")
	}
	return fmt.Sprintf("%s\n\n# skopeo-win v%s\n\n%s\n\n## Build provenance\n\nSource: https://github.com/%s/commit/%s\nBuild, integration tests, and security scans: https://github.com/%s/actions/runs/%s\n\nNative Windows amd64 and arm64 binaries with SHA-256 checksums. CGO is disabled. Executables are not Authenticode signed. ARM64 is cross-compiled and inspected, not runtime-tested.\n", marker(m.RunID), version, summary, m.Repo, m.Commit, m.Repo, m.RunID), nil
}

func (m Manager) State() ([]Ref, []Release, error) {
	var refs []Ref
	var releases []Release
	for _, item := range []struct {
		path string
		refs bool
	}{
		{"git/matching-refs/tags/v", true}, {"releases", false},
	} {
		data, err := m.Run("api", "repos/"+m.Repo+"/"+item.path, "--paginate", "--slurp")
		if err != nil {
			return nil, nil, err
		}
		if item.refs {
			var pages [][]Ref
			if err := json.Unmarshal(data, &pages); err != nil {
				return nil, nil, err
			}
			for _, page := range pages {
				refs = append(refs, page...)
			}
		} else {
			var pages [][]Release
			if err := json.Unmarshal(data, &pages); err != nil {
				return nil, nil, err
			}
			for _, page := range pages {
				releases = append(releases, page...)
			}
		}
	}
	return refs, releases, nil
}

// Files requires exactly the expected files and verifies checksums before mutation.
func Files(dir string) (map[string]string, error) {
	files := map[string]string{}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	for _, arch := range []string{"amd64", "arm64"} {
		name := "skopeo-windows-" + arch + ".exe"
		data, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return nil, err
		}
		sum := sha256.Sum256(data)
		checksum, err := os.ReadFile(filepath.Join(dir, name+".sha256"))
		if err != nil {
			return nil, err
		}
		fields := strings.Fields(string(checksum))
		if len(fields) != 2 || fields[0] != hex.EncodeToString(sum[:]) || fields[1] != name {
			return nil, fmt.Errorf("invalid checksum file for %s", name)
		}
		files[name] = "sha256:" + hex.EncodeToString(sum[:])
		sum = sha256.Sum256(checksum)
		files[name+".sha256"] = "sha256:" + hex.EncodeToString(sum[:])
	}
	if len(entries) != len(files) {
		return nil, fmt.Errorf("unexpected release files")
	}
	return files, nil
}

func ValidateAssets(assets []Asset, expected map[string]string, complete bool) error {
	seen := map[string]bool{}
	for _, asset := range assets {
		if seen[asset.Name] || expected[asset.Name] == "" || asset.Digest != expected[asset.Name] {
			return fmt.Errorf("refusing to replace mismatched release asset %s", asset.Name)
		}
		seen[asset.Name] = true
	}
	if complete && len(seen) != len(expected) {
		return fmt.Errorf("published release has missing assets")
	}
	return nil
}

func (m Manager) Publish(version, dir string) error {
	tag := "v" + version
	if _, ok := parse(tag); !ok || tag == LegacyTag {
		return fmt.Errorf("invalid independent release version %q", version)
	}
	notes, err := m.Notes(version)
	if err != nil {
		return err
	}
	expected, err := Files(dir)
	if err != nil {
		return err
	}
	refs, releases, err := m.State()
	if err != nil {
		return err
	}
	if err := validateTagState(tag, m.RunID, refs, releases); err != nil {
		return err
	}
	if err := m.checkTag(refs, tag); err != nil {
		return err
	}
	if err := m.checkMainHistory(); err != nil {
		return err
	}
	var current *Release
	for i := range releases {
		if releases[i].Tag == tag {
			current = &releases[i]
			break
		}
	}
	if current != nil {
		if current.ID <= 0 {
			return fmt.Errorf("release %s has no valid identity", tag)
		}
		if !strings.Contains(current.Body, marker(m.RunID)) {
			return fmt.Errorf("release %s belongs to a different run", tag)
		}
		if err := ValidateAssets(current.Assets, expected, !current.Draft); err != nil {
			return err
		}
		if !current.Draft {
			return nil
		} // Published releases are immutable, including on reruns.
	} else {
		created, createErr := m.Run("api", "--method", "POST", "repos/"+m.Repo+"/releases", "-f", "tag_name="+tag, "-f", "target_commitish="+m.Commit, "-f", "name=skopeo-win "+tag, "-f", "body="+notes, "-F", "draft=true")
		err = createErr
		if err != nil {
			return err
		}
		current = &Release{}
		if err := json.Unmarshal(created, current); err != nil {
			return fmt.Errorf("reading created draft: %w", err)
		}
		if current.ID <= 0 || current.Tag != tag || !current.Draft || !strings.Contains(current.Body, marker(m.RunID)) {
			return fmt.Errorf("created release does not match the requested draft")
		}
	}
	for _, name := range []string{"skopeo-windows-amd64.exe", "skopeo-windows-amd64.exe.sha256", "skopeo-windows-arm64.exe", "skopeo-windows-arm64.exe.sha256"} {
		found := false
		for _, asset := range current.Assets {
			if asset.Name == name {
				found = true
			}
		}
		if found {
			continue
		}
		if _, err := m.Run("release", "upload", tag, filepath.Join(dir, name), "--repo", m.Repo); err != nil {
			return err
		}
	}
	refs, releases, err = m.State()
	if err != nil {
		return err
	}
	if err := m.checkTag(refs, tag); err != nil {
		return err
	}
	for _, r := range releases {
		if r.Tag != tag {
			continue
		}
		if r.ID != current.ID || !strings.Contains(r.Body, marker(m.RunID)) {
			return fmt.Errorf("release identity or ownership changed during upload")
		}
		if err := ValidateAssets(r.Assets, expected, true); err != nil {
			return err
		}
		if !r.Draft {
			return nil
		}
		_, err = m.Run("api", "--method", "PATCH", "repos/"+m.Repo+"/releases/"+strconv.FormatInt(current.ID, 10), "-F", "draft=false", "-f", "make_latest=true")
		return err
	}
	return fmt.Errorf("draft release %s disappeared", tag)
}
